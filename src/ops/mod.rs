/// Build the [`OpRegistry`] for tensor from the `atoms.yaml` spec —
/// `{fn, sig}` arrow values instead of hand-wired declarations (P-013).
/// Every atom's `sig` reaches typecheck via
/// [`OpRegistry::register_with_sig`] (T-148); ops carry no runtime
/// checkers (axioms trusted).
pub fn tensor_op_registry() -> OpRegistry {
    let decls =
        crate::atoms::module_atoms(ATOMS_YAML, "tensor").expect("atoms.yaml: tensor module decls");
    crate::atoms::registry_from_atoms(&decls, &tensor_impls())
        .expect("atoms.yaml: tensor op registry")
}

