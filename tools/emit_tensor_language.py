#!/usr/bin/env python3
"""Emit the tensor ``Language`` fragment — ops/attrs/guards as data.

ADR-0174 P1 / ADR-0044 ops-as-data: the ``tensor.*`` host surface is
declared as ``handl-language`` fragment rows (``AstShapeDef`` YAML)
instead of living only as ``op "tensor.X"`` lines in
``src/index.hnl`` + the Rust ``OpRegistry``.  The emitted file is
``data/language/tensor/ast.yaml`` — an *overlay* fragment: consumers
merge its rows into any ``Language`` via ``merge_ast_fragment`` (the
same path ``language_from_dir``/``merge_lang_fragments`` use for
``ast.yaml``); no shell files are emitted because the tensor domain
adds node kinds to a base language, it does not define one.

Sources (all read-only, all in this repo):

* ``src/index.hnl`` — the handwritten ``op "tensor.X" : <sig> -> <ret>``
  declarations (the seam ops the Rust impls own).  The signature regex
  is deliberately broader than ``mlopt_host_tensor.surface``'s
  ``->\\s*(\\S+)$``: ``tensor.shape`` returns ``(List Int)`` — a
  two-token type the graphopt-side collector misses (its
  ``host_surface.json`` carries 237 ops; this fragment carries the
  full 238).
* ``target/debug/aten_port_gen --emit-spec`` — the resolved spec for
  the ATen-ported ops (``tools/aten_port_list.txt`` +
  ``tools/aten_schemas.json`` → ``src/ops/aten_generated.rs``),
  carrying ``min_args``/``max_args``/``schema``/``status``.  Build the
  binary first if absent: ``cargo build --bin aten_port_gen``.
* ``mlopt_core.attrs`` (``ATTR_SCHEMA``/``ATTR_REQUIRED`` — eqsat
  ``packages/mlopt-core``) — the canonical per-op attr vocabulary the
  mlopt game already validates at mint time.  Resolved by importing
  ``mlopt_core.attrs``; ``EQSAT_DIR``/``MLCORE_SRC`` or the
  ``../eqsat`` sibling checkout supply the source path.  Ops absent
  from the schema get an honestly *open* attrs block — undeclared
  attrs pass, exactly like ``Op.make(validate=False)`` terms.

Row shape (mirrors ``discoverykit.handl.opdef_to_handl`` /
``vocabdir._ast_shape_row`` — the established op→fragment encoding):

* ``node_kind`` is the qualified op name (``tensor.abs``).
* ``children`` are ``arg{i}`` roles — required up to ``min_args``,
  ``optional: true`` through ``max_args`` (positional-optional
  convention, e.g. ``conv2d``'s trailing ``bias?/stride?/…``).  Ops
  whose arity the surface leaves open (handwritten decls carry no
  ``min_args``/``max_args``) emit *no* ``children`` — the
  ``AstShapeDef`` opaque/positional fallback, not a guessed arity.
* ``payload_schema`` is a real JSON Schema for the node payload
  (``attrs`` object + ``children`` array bounds) plus a ``tensor_op``
  extension block carrying the full surface row and the attrs schema
  (``positions``: arg-position → canonical name; ``names``: every
  accepted spelling — canonical names and declared ``argN``
  aliases; ``required``: ``ATTR_REQUIRED`` names, enforced by
  mlopt only on *fully-attributed* terms so the fragment records
  them as data, not as unconditional JSON-Schema ``required``).

Usage::

    python3 tools/emit_tensor_language.py [--check]

``--check`` exits non-zero when the artifact is stale — the drift
gate a test or CI lane can run.  Requires PyYAML and an importable
``mlopt_core.attrs`` (see above).
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

import yaml

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "data" / "language" / "tensor" / "ast.yaml"

# ``op "tensor.conv2d" : Value... -> Tensor`` — handwritten decls.  The
# result side is ``(.+?)$`` (rest of line), NOT ``\\S+$``: ``tensor.shape``
# returns ``(List Int)``, which the graphopt-side collector's ``\\S+``
# pattern silently drops (see module docstring).
_OP_DECL = re.compile(
    r'^op "(tensor\.[A-Za-z0-9_]+)"\s*:\s*(.+?)\s*->\s*(.+?)\s*$',
    re.MULTILINE,
)

_HEADER = """\
# Tensor Language fragment — ADR-0174 P1 (ops/attrs/guards as data).
#
# GENERATED by tools/emit_tensor_language.py from src/index.hnl op decls
# + `aten_port_gen --emit-spec` + mlopt_core.attrs (ATTR_SCHEMA /
# ATTR_REQUIRED).  Do not hand-edit; regenerate:
#
#     python3 tools/emit_tensor_language.py [--check]
#
# One AstShapeDef per `tensor.*` op — an overlay fragment: merge rows
# into a Language via `merge_ast_fragment` (or drop the file into a
# fragment dir's ast.yaml slot).  `node_kind` is the qualified op name;
# `payload_schema.tensor_op` carries the surface row (signature,
# min/max args, status, kind, ATen schema) and the attrs schema
# (positions/names/required — the guard data typecheck/lint engines
# read; AttrEq/SameAttr/KindAt/ChildCount are the law-guard condition
# vocabulary these attrs ride under, ADR-0173).
"""


def _find_mlopt_core_attrs() -> Any:
    """Import ``mlopt_core.attrs`` from a sibling eqsat checkout."""
    candidates = []
    for env in ("MLCORE_SRC", "EQSAT_DIR"):
        v = __import__("os").environ.get(env)
        if v:
            candidates.append(Path(v))
    candidates += [
        REPO.parent / "eqsat" / "packages" / "mlopt-core" / "src",
        REPO.parent / "mlopt" / "packages" / "mlopt-core" / "src",
    ]
    for cand in candidates:
        if (cand / "mlopt_core" / "attrs.py").is_file():
            sys.path.insert(0, str(cand))
            break
    try:
        from mlopt_core import attrs  # noqa: PLC0415
    except ImportError as e:
        raise SystemExit(
            "mlopt_core.attrs not importable — point MLCORE_SRC or "
            "EQSAT_DIR at an eqsat checkout "
            "(packages/mlopt-core/src), or `uv sync` graphopt's venv "
            f"and run with it. ({e})"
        ) from e
    return attrs


def _index_hnl_ops() -> dict[str, dict[str, Any]]:
    """Handwritten ``op "tensor.X" : sig`` decls from ``index.hnl``."""
    text = (REPO / "src" / "index.hnl").read_text()
    ops: dict[str, dict[str, Any]] = {}
    for m in _OP_DECL.finditer(text):
        name, params, result = m.group(1), m.group(2), m.group(3)
        ops[name] = {
            "op": name,
            "signature": f"{params.strip()} -> {result.strip()}",
            "min_args": None,
            "max_args": None,
            "status": "Handwritten",
            "kind": "handwritten",
            "reason": "",
        }
    return ops


def _emit_spec() -> list[dict[str, Any]]:
    """Run ``aten_port_gen --emit-spec``; return its ``ops`` array."""
    binary = REPO / "target" / "debug" / "aten_port_gen"
    if not binary.is_file():
        raise SystemExit(
            f"{binary} not built — "
            "cargo build --bin aten_port_gen (repo root)"
        )
    out = subprocess.run(
        [str(binary), "--emit-spec"],
        cwd=REPO,
        capture_output=True,
        text=True,
        timeout=120,
    )
    if out.returncode != 0:
        raise SystemExit(
            f"aten_port_gen --emit-spec failed: {out.stderr.strip()}"
        )
    return json.loads(out.stdout)["ops"]


def collect_ops() -> list[dict[str, Any]]:
    """The unified op→signature table (generated wins on name clashes)."""
    ops = _index_hnl_ops()
    for entry in _emit_spec():
        name = entry["op"]
        ops[name] = {
            "op": name,
            "signature": entry.get("signature", ""),
            "schema": entry.get("schema", ""),
            "min_args": entry.get("min_args"),
            "max_args": entry.get("max_args"),
            "status": entry.get("status", ""),
            "kind": "generated",
            "reason": entry.get("reason", ""),
        }
    return sorted(ops.values(), key=lambda o: o["op"])


def _attrs_schema(op: str, mlopt_attrs: Any) -> dict[str, Any]:
    """The attrs declaration for one op, as data.

    ``positions`` is ``ATTR_SCHEMA[bare]`` (arg-position → canonical
    name); ``names`` is every spelling mlopt accepts — the canonical
    names plus the declared ``argN`` positional aliases;
    ``required`` is ``ATTR_REQUIRED[bare]`` — recorded as data with
    the honest caveat that mlopt enforces it only on fully-attributed
    terms (zero-attr and non-declared-extra terms pass).
    """
    bare = op.split(".", 1)[1]
    schema = mlopt_attrs.ATTR_SCHEMA.get(bare, {})
    required = sorted(mlopt_attrs.ATTR_REQUIRED.get(bare, ()))
    names = sorted(set(schema.values()) | {f"arg{i}" for i in schema})
    return {
        "source": "mlopt_core.attrs" if schema or required else None,
        "positions": {str(i): n for i, n in sorted(schema.items())},
        "names": names,
        "required": required,
        # mlopt's contract: ops with no schema pass untouched, and
        # undeclared non-positional names are never rejected — attrs
        # are open by default; the schema bounds spellings, it does
        # not close the map.
        "open": True,
    }


def _ast_row(op: dict[str, Any], mlopt_attrs: Any) -> dict[str, Any]:
    """Render one surface op as an ``AstShapeDef`` fragment row."""
    min_args = op.get("min_args")
    max_args = op.get("max_args")
    row: dict[str, Any] = {
        "id": f"ast.{op['op'].replace('.', '.')}",
        "node_kind": op["op"],
    }
    # Fixed/known arity → arg{i} roles, optional past min_args (the
    # positional-optional convention).  Open arity (handwritten decls
    # carry no min/max) → no `children`: the shape stays opaque and
    # engines keep the positional fallback rather than a guessed arity.
    if min_args is not None and max_args is not None:
        row["children"] = [
            {"role": f"arg{i}", **({"optional": True} if i >= min_args else {})}
            for i in range(max_args)
        ]
    children_schema: dict[str, Any] = {"type": "array"}
    if min_args is not None:
        children_schema["minItems"] = min_args
    if max_args is not None:
        children_schema["maxItems"] = max_args
    attrs_schema = _attrs_schema(op["op"], mlopt_attrs)
    tensor_op: dict[str, Any] = {
        "op": op["op"],
        "signature": op.get("signature", ""),
        "min_args": min_args,
        "max_args": max_args,
        "status": op.get("status", ""),
        "kind": op.get("kind", ""),
        "attrs_schema": attrs_schema,
    }
    if op.get("schema"):
        tensor_op["schema"] = op["schema"]
    if op.get("reason"):
        tensor_op["reason"] = op["reason"]
    row["payload_schema"] = {
        "type": "object",
        "properties": {
            "attrs": {
                "type": "object",
                # Declared spellings only — canonical names and the
                # argN aliases ATTR_SCHEMA admits.  additionalProperties
                # stays true: undeclared extras are legal partial terms.
                "properties": {n: {} for n in attrs_schema["names"]},
                "additionalProperties": True,
            },
            "children": children_schema,
        },
        "required": ["children"],
        # Extension block — handl ignores unknown payload_schema keys;
        # tensor consumers (typecheck/lint/search) read the surface row
        # and the attrs guard data here.  Same posture as the
        # `mlopt.op` extension vocabdir._ast_shape_row emits.
        "tensor_op": tensor_op,
    }
    return row


def render(ops: list[dict[str, Any]], mlopt_attrs: Any) -> str:
    """The canonical artifact text."""
    rows = [_ast_row(o, mlopt_attrs) for o in ops]
    return _HEADER + yaml.safe_dump(
        rows, sort_keys=False, allow_unicode=True, width=100
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="compare against the artifact without writing",
    )
    ap.add_argument(
        "--out",
        type=Path,
        default=OUT,
        help=f"output path (default: {OUT})",
    )
    args = ap.parse_args(argv)

    mlopt_attrs = _find_mlopt_core_attrs()
    text = render(collect_ops(), mlopt_attrs)

    if args.check:
        if not args.out.is_file():
            print(f"{args.out}: missing — run the generator", file=sys.stderr)
            return 1
        if args.out.read_text() != text:
            print(
                f"{args.out}: stale — run tools/emit_tensor_language.py",
                file=sys.stderr,
            )
            return 1
        print(f"{args.out}: fresh")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"wrote {args.out} ({text.count('- id: ')} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
